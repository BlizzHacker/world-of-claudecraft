#!/usr/bin/env node
// Generate Traefik dynamic-config routers+services for every realm stage and the
// matching Cloudflare DNS record list. Mirrors the existing
// /etc/traefik/conf.d/crypticrealm-realms.yml format on CT 107.
//
//   node scripts/admin/gen-traefik-stages.mjs           # print YAML
//   node scripts/admin/gen-traefik-stages.mjs --dns      # print DNS records
//
// dev/alpha rings are restricted: they get the same TLS route but a noindex
// header middleware so they aren't crawled (auth gating is enforced in-app via
// CR_STAGE_RESTRICTED + the role check).
import { STAGES, REALMS, stagePort, stageHost, STAGE_RESTRICTED } from './stages.config.mjs';

const TARGET_IP = process.env.CR_NODE_IP || '192.168.0.171';
const dnsMode = process.argv.includes('--dns');

const hosts = [];
const routers = [];
const services = [];

for (const realmId of Object.keys(REALMS)) {
  for (const stage of STAGES) {
    const host = stageHost(realmId, stage);
    const port = stagePort(realmId, stage);
    const name = `cr-${realmId}-${stage}`;
    hosts.push({ host, restricted: STAGE_RESTRICTED[stage] });
    const mids = STAGE_RESTRICTED[stage]
      ? '[crypticrealm-headers, chain-no-auth, cr-noindex]'
      : '[crypticrealm-headers, chain-no-auth]';
    routers.push(
      `    ${name}-rtr:\n` +
      `      rule: "Host(\`${host}\`)"\n` +
      `      entryPoints: [websecure]\n` +
      `      middlewares: ${mids}\n` +
      `      service: ${name}-svc\n` +
      `      priority: 100\n` +
      `      tls:\n` +
      `        certResolver: myresolver`,
    );
    services.push(
      `    ${name}-svc:\n` +
      `      loadBalancer:\n` +
      `        servers:\n` +
      `          - url: "http://${TARGET_IP}:${port}"`,
    );
  }
}

if (dnsMode) {
  console.log('# Cloudflare DNS — add each as a proxied (or DNS-only) A/CNAME to the edge.');
  console.log('# If you have a wildcard *.crypticrealm.com already, only the deeper');
  console.log('# *.<realm>.crypticrealm.com hosts need adding.');
  for (const h of hosts) {
    console.log(`${h.host}${h.restricted ? '   # restricted (admin/mod/tester)' : ''}`);
  }
} else {
  console.log('## Per-realm-STAGE Traefik routes — generated by gen-traefik-stages.mjs');
  console.log('## Drop into LXC 107 /etc/traefik/conf.d/crypticrealm-stages.yml then');
  console.log('## `systemctl reload traefik`. Requires a cr-noindex middleware for the');
  console.log('## restricted rings (add to the shared middlewares file if missing).');
  console.log('http:');
  console.log('  routers:');
  console.log(routers.join('\n\n'));
  console.log('');
  console.log('  services:');
  console.log(services.join('\n\n'));
}
