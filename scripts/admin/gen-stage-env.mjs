#!/usr/bin/env node
// Generate per-realm-per-stage env files into env.d/<realm>-<stage>.env.
//
//   node scripts/admin/gen-stage-env.mjs            # write env.d/*.env
//   node scripts/admin/gen-stage-env.mjs --print    # dry-run to stdout
//
// Each file carries REALM_NAME, REALM_TYPE, PORT, CR_STAGE, CR_PLATINUM_MULT,
// CR_STAGE_RESTRICTED, and the shared REALMS directory CSV so any stage the
// player lands on can list + switch to every other realm/stage.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import {
  STAGES, REALMS, stagePort, stageInstance, stageHost, stageName, stageRealmName,
  STAGE_PLATINUM, STAGE_RESTRICTED, STAGE_GIT_REF,
} from './stages.config.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../..');
const envDir = resolve(repoRoot, 'env.d');
const dryRun = process.argv.includes('--print');
// --directory-csv: print ONLY the `REALMS=` directory line and exit. Used by
// update.sh to keep the apex /opt/cryptic-realm/.env directory in sync with
// stages.config (the apex .env is hand-maintained/untracked, so without this it
// drifts — which is exactly why crypticrealm.com once advertised only 10 stale
// flat realms instead of the full 24 realm×stage set / 96 character combos).
const directoryCsvMode = process.argv.includes('--directory-csv');

// Build the directory CSV: every realm's LIVE ring is always listed; the
// restricted stages (alpha/dev) are appended so testers/admins can reach them.
// Entry form: Name=publicURL=Type  (matches the existing REALMS env contract).
const directoryEntries = [];
for (const realmId of Object.keys(REALMS)) {
  for (const stage of STAGES) {
    directoryEntries.push(`${stageName(realmId, stage)}=https://${stageHost(realmId, stage)}=${REALMS[realmId].type}`);
  }
}
const directoryCsv = directoryEntries.join(',');

if (directoryCsvMode) {
  process.stdout.write(`REALMS=${directoryCsv}\n`);
  process.exit(0);
}

if (!dryRun) mkdirSync(envDir, { recursive: true });

let count = 0;
for (const realmId of Object.keys(REALMS)) {
  for (const stage of STAGES) {
    const port = stagePort(realmId, stage);
    const inst = stageInstance(realmId, stage);
    const body = [
      `# ${stageName(realmId, stage)} — generated by scripts/admin/gen-stage-env.mjs`,
      `# Layered on /opt/cryptic-realm/.env by the systemd template. Do not edit by hand;`,
      `# edit scripts/admin/stages.config.mjs and regenerate.`,
      // REALM_NAME = the server's realm identity AND DB partition key. Each
      // stage is its OWN world ("Cryptic Realm" / "Cryptic Realm Beta" / ...),
      // so alpha is reset-prone and promotion migrates characters between rings.
      // CR_STAGE_LABEL carries the bracketed display label for the client UI.
      `REALM_NAME=${stageRealmName(realmId, stage)}`,
      `CR_STAGE_LABEL=${stageName(realmId, stage)}`,
      `REALM_TYPE=${REALMS[realmId].type}`,
      `PORT=${port}`,
      `CR_STAGE=${stage}`,
      `CR_REALM_ID=${realmId}`,
      `CR_PLATINUM_MULT=${STAGE_PLATINUM[stage]}`,
      `CR_STAGE_RESTRICTED=${STAGE_RESTRICTED[stage] ? '1' : '0'}`,
      `CR_GIT_REF=${STAGE_GIT_REF[stage]}`,
      `CR_WORKDIR=${process.env.STAGES_ROOT || '/opt/cr-stages'}/${realmId}/${stage}`,
      `WEB_ORIGINS=https://${stageHost(realmId, stage)},https://crypticrealm.com`,
      `REALMS=${directoryCsv}`,
      '',
    ].join('\n');
    if (dryRun) {
      console.log(`\n----- env.d/${inst}.env (port ${port}) -----\n${body}`);
    } else {
      writeFileSync(resolve(envDir, `${inst}.env`), body, 'utf8');
    }
    count++;
  }
}

console.error(`${dryRun ? 'would write' : 'wrote'} ${count} stage env files to env.d/`);
